#!/usr/bin/env python3
"""用 Tailwind 獨立 CLI（不需要 Node／npm）把前端 class 編成靜態 CSS。

產出 internal/static/js/vendor/tailwind.css 並提交進 repo；index.html 預設載入它，
取代 407KB 的 Play CDN（tailwind.js，每次載入都在瀏覽器內即時編譯）。
設定來源仍是 index.html 內嵌的 `tailwind.config = ...`，所以只有一份。

用法：
  python scripts/build-css.py            # 重新產生並寫回
  python scripts/build-css.py --check    # 只比對，過期則以非零結束（CI、發版前使用）

改了任何 className（或 index.html 的 tailwind.config、自訂 <style>）後要重新執行。
開發時想即時編譯可設環境變數 CMA_TAILWIND_JIT=1，改回 Play CDN。

CLI 版本與 SHA-256 固定在下方；下載後每次執行都會驗證。
"""
import argparse
import hashlib
import os
import platform
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

VERSION = "3.4.17"  # 必須與 internal/static/js/vendor/tailwind.js（Play CDN）同版，輸出才一致
CLI_SHA256 = {
    "windows-x64": "67f1c5e3f5a03406a7bf5badf5ada09b79f3ae78ec43450c15f7e983068da346",
    "windows-arm64": "76f516476784c00f1562160b5758e3d8f0e6c48957efb26b5b50fbdfd76aa382",
    "linux-x64": "7d24f7fa191d2193b78cd5f5a42a6093e14409521908529f42d80b11fde1f1d4",
    "linux-arm64": "69b1378b8133192d7d2feb12a116fa12d035594f58db3eff215879e4ad8cf39b",
    "macos-x64": "6cbdad74be776c087ffa5e9a057512c54898f9fe8828d3362212dfe32fc933a3",
    "macos-arm64": "a1d0c7985759accca0bf12e51ac1dcbf0f6cf2fffb62e6e0f62d091c477a10a3",
}

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "internal" / "static"
OUT = STATIC / "js" / "vendor" / "tailwind.css"
HEADER = f"/* Generated by scripts/build-css.py — Tailwind CSS v{VERSION}. Do not edit; run the script. */\n"


def platform_key() -> str:
    machine = platform.machine().lower()
    arch = "arm64" if machine in ("arm64", "aarch64") else "x64"
    if sys.platform.startswith("win"):
        return f"windows-{arch}"
    if sys.platform == "darwin":
        return f"macos-{arch}"
    return f"linux-{arch}"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def ensure_cli() -> Path:
    key = platform_key()
    want = CLI_SHA256[key]
    cache = Path(os.environ.get("CMA_TOOLS_DIR") or Path.home() / ".cache" / "claude-miniapp" / "tools")
    cache.mkdir(parents=True, exist_ok=True)
    exe = cache / f"tailwindcss-{VERSION}-{key}{'.exe' if key.startswith('windows') else ''}"
    if exe.exists() and sha256(exe) == want:
        return exe
    url = f"https://github.com/tailwindlabs/tailwindcss/releases/download/v{VERSION}/tailwindcss-{key}{'.exe' if key.startswith('windows') else ''}"
    print(f"下載 Tailwind CLI v{VERSION}（{key}）…", file=sys.stderr)
    tmp = exe.with_suffix(exe.suffix + ".part")
    urllib.request.urlretrieve(url, tmp)
    got = sha256(tmp)
    if got != want:
        tmp.unlink(missing_ok=True)
        sys.exit(f"Tailwind CLI 的 SHA-256 不符（期望 {want}，實得 {got}），拒絕使用")
    tmp.replace(exe)
    exe.chmod(0o755)
    return exe


def inline_config() -> str:
    html = (STATIC / "index.html").read_text(encoding="utf-8")
    m = re.search(r"<script>\s*(tailwind\.config = .*?)</script>", html, re.S)
    if not m:
        sys.exit("index.html 找不到內嵌的 tailwind.config")
    return m.group(1)


def build() -> bytes:
    cli = ensure_cli()
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "tailwind-config.js").write_text(inline_config() + "\n", encoding="utf-8")
        static = STATIC.as_posix()
        (tmp / "tailwind.config.cjs").write_text(
            "global.tailwind = {};\n"
            "require('./tailwind-config.js');\n"
            "module.exports = {\n"
            f"  content: ['{static}/index.html', '{static}/js/**/*.js', '!{static}/js/vendor/**'],\n"
            "  ...global.tailwind.config,\n"
            "};\n",
            encoding="utf-8",
        )
        (tmp / "input.css").write_text("@tailwind base;\n@tailwind components;\n@tailwind utilities;\n", encoding="utf-8")
        out = tmp / "out.css"
        r = subprocess.run(
            [str(cli), "-c", str(tmp / "tailwind.config.cjs"), "-i", str(tmp / "input.css"), "-o", str(out), "--minify"],
            capture_output=True, text=True,
        )
        if r.returncode != 0 or not out.exists():
            sys.exit(f"Tailwind CLI 失敗：\n{r.stdout}\n{r.stderr}")
        css = out.read_bytes().replace(b"\r\n", b"\n")
    return HEADER.encode("utf-8") + css


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="只比對，不寫檔；過期時以 1 結束")
    args = ap.parse_args()
    fresh = build()
    current = OUT.read_bytes() if OUT.exists() else b""
    if args.check:
        if fresh != current:
            print(
                "internal/static/js/vendor/tailwind.css 已過期：className、tailwind.config 或自訂樣式有變。\n"
                "請執行 python scripts/build-css.py 並提交結果。",
                file=sys.stderr,
            )
            return 1
        print(f"tailwind.css 是最新的（{len(current)} bytes）")
        return 0
    if fresh == current:
        print(f"tailwind.css 沒有變動（{len(current)} bytes）")
        return 0
    OUT.write_bytes(fresh)
    print(f"已寫入 {OUT.relative_to(ROOT)}（{len(fresh)} bytes）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
